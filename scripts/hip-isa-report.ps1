<#
.SYNOPSIS
    Unbundles compiled HIP .hsaco code objects for gfx1100 and gfx1201, runs Radeon GPU Analyzer (RGA),
    and generates an ISA resource report (VGPR, SGPR, spills, LDS, ISA size).

.DESCRIPTION
    Leverages clang-offload-bundler from the HIP SDK to extract ELF objects from .hsaco bundles,
    then executes RGA in binary mode (-s bin) to extract register allocation and memory statistics.
    Used in Phase 3/4 PRs to compare before/after ISA efficiency (H2.8).

.PARAMETER Arch
    Optional architecture filter ('gfx1100', 'gfx1201', or 'all'). Default: 'all'.

.PARAMETER Kernel
    Optional kernel name filter pattern (e.g. 'gemv', 'rmsnorm').

.PARAMETER OutFile
    Optional path to write a Markdown report to.

.PARAMETER AsMarkdown
    Output table in Markdown format instead of PowerShell table format.
#>
[CmdletBinding()]
param(
    [ValidateSet("all", "gfx1100", "gfx1201")]
    [string]$Arch = "all",

    [string]$Kernel = "",

    [string]$OutFile = "",

    [switch]$AsMarkdown
)

$ErrorActionPreference = "Stop"

# 1. Validate environment
if (-not $env:HIP_PATH) {
    Write-Error "HIP_PATH environment variable is not set."
    exit 1
}
$bundler = Join-Path $env:HIP_PATH "bin\clang-offload-bundler.exe"
if (-not (Test-Path $bundler)) {
    Write-Error "clang-offload-bundler not found at '$bundler'."
    exit 1
}

if (-not $env:DOTLLM_RDTS) {
    Write-Error "DOTLLM_RDTS environment variable is not set. Point it to the Radeon Developer Tool Suite directory (W16)."
    exit 1
}
$rga = Join-Path $env:DOTLLM_RDTS "rga.exe"
if (-not (Test-Path $rga)) {
    Write-Error "rga.exe not found at '$rga'."
    exit 1
}

$repoRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
$hipObjDir = Join-Path $repoRoot "src\DotLLM.Hip\obj"

# Ensure hsaco files exist
$hsacoFiles = Get-ChildItem -Path $hipObjDir -Recurse -Filter "*.hsaco" -ErrorAction SilentlyContinue
if (-not $hsacoFiles) {
    Write-Host "[hip-isa-report] No .hsaco files found in obj. Building DotLLM.Hip in Release mode..."
    & dotnet build (Join-Path $repoRoot "src\DotLLM.Hip\DotLLM.Hip.csproj") -c Release | Out-Null
    $hsacoFiles = Get-ChildItem -Path $hipObjDir -Recurse -Filter "*.hsaco"
    if (-not $hsacoFiles) {
        Write-Error "Failed to locate .hsaco files after building DotLLM.Hip."
        exit 1
    }
}

$archsToReport = if ($Arch -eq "all") { @("gfx1100", "gfx1201") } else { @($Arch) }

# Create temporary scratch directory
$scratchDir = Join-Path ([System.IO.Path]::GetTempPath()) ("hip_isa_" + [System.Guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Path $scratchDir -Force | Out-Null

try {
    $results = [System.Collections.Generic.List[PSCustomObject]]::new()

    foreach ($targetArch in $archsToReport) {
        # Find hsaco files for this arch (prefer Release, fallback to latest)
        $archFiles = $hsacoFiles | Where-Object { $_.DirectoryName -like "*\$targetArch" } |
            Group-Object Name | ForEach-Object { $_.Group | Sort-Object LastWriteTime -Descending | Select-Object -First 1 }

        if (-not $archFiles) {
            Write-Warning "No .hsaco files found for $targetArch."
            continue
        }

        foreach ($hsaco in $archFiles) {
            $baseName = [System.IO.Path]::GetFileNameWithoutExtension($hsaco.Name)
            if ($Kernel -and ($baseName -notmatch $Kernel)) {
                continue
            }

            $unbundleTarget = "hipv4-amdgcn-amd-amdhsa--$targetArch"
            $elfFile = Join-Path $scratchDir "$($baseName)_$targetArch.elf"

            # 2. Unbundle code object
            $unbundleOut = & $bundler --type=o --unbundle --targets=$unbundleTarget --input="$($hsaco.FullName)" --output="$elfFile" 2>&1
            if ($LASTEXITCODE -ne 0 -or -not (Test-Path $elfFile)) {
                Write-Warning "Failed to unbundle $($hsaco.Name) for $($targetArch): $unbundleOut"
                continue
            }

            # 3. Run RGA binary disassembly and resource analysis
            $rgaWorkDir = Join-Path $scratchDir "rga_$($baseName)_$targetArch"
            New-Item -ItemType Directory -Path $rgaWorkDir -Force | Out-Null

            $statsPrefix = Join-Path $rgaWorkDir "stats.csv"
            $isaPrefix = Join-Path $rgaWorkDir "isa.txt"

            $rgaOut = & $rga -s bin -a "$statsPrefix" --isa "$isaPrefix" "$elfFile" 2>&1
            if ($LASTEXITCODE -ne 0) {
                Write-Warning "RGA failed for $($hsaco.Name) on $($targetArch): $rgaOut"
                continue
            }

            # 4. Parse statistics CSV files generated by RGA
            $statFiles = Get-ChildItem -Path $rgaWorkDir -Filter "*_stats.csv"
            foreach ($statFile in $statFiles) {
                # Format: <targetArch>_<kernelSymbol>_stats.csv
                $kernelName = $statFile.Name -replace "^$($targetArch)_", "" -replace "_stats\.csv$", ""
                if ($Kernel -and ($kernelName -notmatch $Kernel)) {
                    continue
                }

                $csvContent = Import-Csv -Path $statFile.FullName -ErrorAction SilentlyContinue
                if ($csvContent) {
                    $row = $csvContent[0]
                    $results.Add([PSCustomObject]@{
                        Arch        = $targetArch
                        File        = $baseName
                        Kernel      = $kernelName
                        VGPR        = [int]($row.USED_VGPRs)
                        SGPR        = [int]($row.USED_SGPRs)
                        VGPR_Spill  = [int]($row.VGPR_SPILLS)
                        SGPR_Spill  = [int]($row.SGPR_SPILLS)
                        LDS_Bytes   = [int]($row.USED_LDS_BYTES)
                        ISA_Bytes   = [int]($row.ISA_SIZE)
                    })
                }
            }
        }
    }

    $sortedResults = $results | Sort-Object Arch, File, Kernel

    # Display or export
    if ($AsMarkdown -or $OutFile) {
        $sb = [System.Text.StringBuilder]::new()
        [void]$sb.AppendLine("# HIP Kernel ISA Resource Report (H2.8)")
        [void]$sb.AppendLine("")
        [void]$sb.AppendLine("> Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') | RGA 2.15.0 | HIP SDK 7.2.3")
        [void]$sb.AppendLine("")

        foreach ($archGroup in ($sortedResults | Group-Object Arch)) {
            [void]$sb.AppendLine("## Architecture: $($archGroup.Name)")
            [void]$sb.AppendLine("")
            [void]$sb.AppendLine("| File | Kernel | VGPR | SGPR | Spills (V/S) | LDS (B) | ISA (B) |")
            [void]$sb.AppendLine("|---|---|---:|---:|---:|---:|---:|")
            foreach ($item in $archGroup.Group) {
                $spills = "$($item.VGPR_Spill)/$($item.SGPR_Spill)"
                [void]$sb.AppendLine("| $($item.File) | $($item.Kernel) | $($item.VGPR) | $($item.SGPR) | $spills | $($item.LDS_Bytes) | $($item.ISA_Bytes) |")
            }
            [void]$sb.AppendLine("")
        }

        $mdText = $sb.ToString()
        if ($OutFile) {
            Set-Content -Path $OutFile -Value $mdText -Encoding utf8
            Write-Host "[hip-isa-report] Wrote report to '$OutFile'."
        }
        if ($AsMarkdown -or (-not $OutFile)) {
            Write-Output $mdText
        }
    } else {
        $sortedResults | Format-Table -Property Arch, File, Kernel, VGPR, SGPR, @{N='Spills(V/S)';E={"$($_.VGPR_Spill)/$($_.SGPR_Spill)"}}, LDS_Bytes, ISA_Bytes -AutoSize
    }

} finally {
    if (Test-Path $scratchDir) {
        Remove-Item -Path $scratchDir -Recurse -Force -ErrorAction SilentlyContinue
    }
}
